-- ─────────────────────────────────────────────────────────────
-- TABLE 1: user_mistakes
-- Stores every question a user answered incorrectly so they can
-- revisit and practice them in the Mistake Journal.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.user_mistakes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     UUID   REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  topic_id    BIGINT REFERENCES public.topics(id)   ON DELETE CASCADE NOT NULL,
  subject_id  TEXT   REFERENCES public.subjects(id) ON DELETE CASCADE NOT NULL,
  chapter_key TEXT   NOT NULL,
  question_index INTEGER NOT NULL,
  question_text   TEXT,
  correct_answer  TEXT,
  solution        TEXT,
  resolved        BOOLEAN NOT NULL DEFAULT FALSE,
  attempt_count   INTEGER NOT NULL DEFAULT 1,
  resolved_at     TIMESTAMP WITH TIME ZONE,
  created_at      TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
  updated_at      TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
  CONSTRAINT user_mistakes_unique UNIQUE (user_id, topic_id, question_index)
);

CREATE INDEX IF NOT EXISTS idx_user_mistakes_user_id     ON public.user_mistakes(user_id);
CREATE INDEX IF NOT EXISTS idx_user_mistakes_topic_id    ON public.user_mistakes(topic_id);
CREATE INDEX IF NOT EXISTS idx_user_mistakes_resolved    ON public.user_mistakes(resolved);
CREATE INDEX IF NOT EXISTS idx_user_mistakes_subject_id  ON public.user_mistakes(subject_id);

-- ─────────────────────────────────────────────────────────────
-- TABLE 2: spaced_reviews
-- One row per (user, topic) tracking the SM-2 spaced repetition
-- schedule: next review date, interval, ease factor, repetitions.
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.spaced_reviews (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       UUID   REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  topic_id      BIGINT REFERENCES public.topics(id)   ON DELETE CASCADE NOT NULL,
  next_review_at TIMESTAMP WITH TIME ZONE NOT NULL,
  interval_days  INTEGER NOT NULL DEFAULT 1,
  ease_factor    NUMERIC(4,2) NOT NULL DEFAULT 2.50,
  repetitions    INTEGER NOT NULL DEFAULT 0,
  updated_at     TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
  CONSTRAINT spaced_reviews_user_topic_unique UNIQUE (user_id, topic_id)
);

CREATE INDEX IF NOT EXISTS idx_spaced_reviews_user_id        ON public.spaced_reviews(user_id);
CREATE INDEX IF NOT EXISTS idx_spaced_reviews_next_review_at ON public.spaced_reviews(next_review_at);

-- ─────────────────────────────────────────────────────────────
-- TABLE 3: user_notes
-- Personal synthesis scratchpad text saved per (user, topic).
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.user_notes (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    UUID   REFERENCES public.profiles(id) ON DELETE CASCADE NOT NULL,
  topic_id   BIGINT REFERENCES public.topics(id)   ON DELETE CASCADE NOT NULL,
  note_text  TEXT   NOT NULL DEFAULT '',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc', now()) NOT NULL,
  CONSTRAINT user_notes_user_topic_unique UNIQUE (user_id, topic_id)
);

CREATE INDEX IF NOT EXISTS idx_user_notes_user_id  ON public.user_notes(user_id);
CREATE INDEX IF NOT EXISTS idx_user_notes_topic_id ON public.user_notes(topic_id);

