-- ─────────────────────────────────────────────────────────────
-- HELPER: auto-update updated_at on user_mistakes and spaced_reviews
-- ─────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = timezone('utc', now());
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_user_mistakes_updated_at  ON public.user_mistakes;
CREATE TRIGGER trg_user_mistakes_updated_at
  BEFORE UPDATE ON public.user_mistakes
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_spaced_reviews_updated_at ON public.spaced_reviews;
CREATE TRIGGER trg_spaced_reviews_updated_at
  BEFORE UPDATE ON public.spaced_reviews
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS trg_user_notes_updated_at ON public.user_notes;
