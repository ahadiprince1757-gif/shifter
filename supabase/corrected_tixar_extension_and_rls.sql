-- ==========================================================
-- 7. VERIFY ACTIVE RLS POLICIES
-- ==========================================================

SELECT
    schemaname,
    tablename,
    policyname,
    roles,
    cmd
FROM pg_policies
WHERE schemaname = 'public'
ORDER BY tablename, policyname;
