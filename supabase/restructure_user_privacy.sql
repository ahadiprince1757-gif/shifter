-- 4. Apply strict user isolation RLS policies
DROP POLICY IF EXISTS "Users isolated progress select" ON public.progress;
DROP POLICY IF EXISTS "Users isolated progress insert" ON public.progress;
DROP POLICY IF EXISTS "Users isolated progress update" ON public.progress;
